#!/usr/bin/env python3
"""Builds api/app.js: the protected lesson content (src/app.html + src/questions.js),
served only to users with an active subscription. Run after every content change:
    python3 tools/build.py
"""
import json, re, subprocess, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
html = (root/'src/app.html').read_text(encoding='utf8')
q = (root/'src/questions.js').read_text(encoding='utf8')
# turn the questions file into data with node (it is plain JS)
data = subprocess.run(['node','-e',
  "const fs=require('fs');const s=fs.readFileSync(process.argv[1],'utf8');"
  "const f=new Function(s.replace(/\\nconst ALLQ[\\s\\S]*$/,'')+';return {QUESTIONS,QT}');process.stdout.write(JSON.stringify(f()))",
  str(root/'src/questions.js')], capture_output=True, text=True, check=True).stdout
out = f"""// GENERATED by tools/build.py — do not edit by hand.
// GET /api/app → lesson content, only for logged-in users with an active subscription.
const {{ handler, send, getUser, paidUntil, isActive }} = require('./_lib');
const HTML = {json.dumps(html, ensure_ascii=False)};
const DATA = {data};
module.exports = handler(async (req, res) => {{
  const u = await getUser(req);
  const until = await paidUntil(u.id);
  if (!isActive(until)) return send(res, 402, {{ error: 'Geen actief abonnement', paid_until: until }});
  send(res, 200, {{ html: HTML, questions: DATA.QUESTIONS, qt: DATA.QT, paid_until: until }});
}}, ['GET']);
"""
(root/'api/app.js').write_text(out, encoding='utf8')
print('api/app.js', len(out)//1024, 'KB')
